(function applyUsTopDetails() {
  const byKey = new Map(NAMES.map(n => [n.name.toLowerCase(), n]));
  for (const [name, [origin, meaning, nicknames]] of Object.entries(US_TOP_DETAILS)) {
    const entry = byKey.get(name.toLowerCase());
    if (!entry) continue;
    if (!entry.meaning && meaning) entry.meaning = meaning;
    if (!(entry.origin || []).length && origin.length) entry.origin = origin;
    if (!NICKNAMES[entry.name] && nicknames.length) NICKNAMES[entry.name] = nicknames;
  }
})();
